  if (life.len > 300) compatParts.push("Скандинавские рунические чтения связывают длинную линию жизни с благословением Фрейи — богини жизни и плодородия");
  if (compatParts.length === 0) compatParts.push("Ваша ладонь сочетает элементы различных мировых традиций, создавая уникальный рисунок, не имеющий прямых аналогов в классических текстах");

  const compatibility = compatParts.join(". ") + ".";

  // Совет от хироманта
  const advicePool: string[] = [];
  if (heart.len > 200) advicePool.push("Позволяйте себе быть уязвимым — это не слабость, а высшая форма мужества. Те, кто умеют открывать сердце, живут полнее");
