type Pt = { x: number; y: number };

function dist(a: Pt, b: Pt): number {
  return Math.sqrt((b.x - a.x) ** 2 + (b.y - a.y) ** 2);
}

function curveDepth(start: Pt, ctrl: Pt, end: Pt): number {
  const base = dist(start, end);
  if (base === 0) return 0;
  return (2 * Math.abs(start.x * (ctrl.y - end.y) + ctrl.x * (end.y - start.y) + end.x * (start.y - ctrl.y))) / (2 * base);
}

function lineAngle(start: Pt, end: Pt): number {
  return (Math.atan2(end.y - start.y, end.x - start.x) * 180) / Math.PI;
}

interface LineMetrics {
  len: number;
  curv: number;
  angle: number;
  startX: number;
  startY: number;
  endX: number;
  endY: number;
  ctrlX: number;
  ctrlY: number;
}

function computeMetrics(start: Pt, ctrl: Pt, end: Pt): LineMetrics {
  return {
    len: dist(start, end),
    curv: curveDepth(start, ctrl, end),
    angle: lineAngle(start, end),
    startX: start.x,
    startY: start.y,
    endX: end.x,
    endY: end.y,
    ctrlX: ctrl.x,
    ctrlY: ctrl.y,
  };
}

// Пересечение двух линий
function linesCross(lineA: { start: Pt; end: Pt }, lineB: { start: Pt; end: Pt }): boolean {
  const d = (lineA.end.x - lineA.start.x) * (lineB.end.y - lineB.start.y) - (lineA.end.y - lineA.start.y) * (lineB.end.x - lineB.start.x);
  if (Math.abs(d) < 0.001) return false;
  const t = ((lineB.start.x - lineA.start.x) * (lineB.end.y - lineB.start.y) - (lineB.start.y - lineA.start.y) * (lineB.end.x - lineB.start.x)) / d;
  const u = ((lineB.start.x - lineA.start.x) * (lineA.end.y - lineA.start.y) - (lineB.start.y - lineA.start.y) * (lineA.end.x - lineA.start.x)) / d;
  return t >= 0 && t <= 1 && u >= 0 && u <= 1;
}

function midPoint(l: LineData): Pt {
  return {
    x: (l.start.x + 2 * l.control.x + l.end.x) / 4,
    y: (l.start.y + 2 * l.control.y + l.end.y) / 4,
  };
}

function minDistBetweenCurves(a: LineData, b: LineData): number {
  const aMid = midPoint(a);
  const bMid = midPoint(b);
  return dist(aMid, bMid);
}

